#!/usr/bin/env python3
"""Creates tables (Markdown) and charts (PNG) from the CSV files written by IntervalCompare.

Usage: plot_results.py OUTPUT_DIR file1.csv [file2.csv ...]
"""
import csv
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ORDER = ["filib", "tight", "native", "cxsc"]
COLORS = {"filib": "#1f77b4", "tight": "#2ca02c", "native": "#d62728", "cxsc": "#ff7f0e"}


def load(files):
    data, ops = {}, []
    for f in files:
        with open(f) as fh:
            for row in csv.DictReader(fh):
                data.setdefault(row["backend"], {})[row["op"]] = row
                if row["op"] not in ops:
                    ops.append(row["op"])
    return data, ops


def md_table(title, data, ops, backends, key, fmt, best_low=True):
    lines = ["### " + title, "", "| op | " + " | ".join(backends) + " |", "|---|" + "---:|" * len(backends)]
    for op in ops:
        vals = [float(data[b][op][key]) for b in backends]
        best = min(vals) if best_low else max(vals)
        cells = [("**%s**" % fmt(v)) if v == best else fmt(v) for v in vals]
        lines.append("| %s | %s |" % (op, " | ".join(cells)))
    return "\n".join(lines) + "\n"


def bar_chart(path, title, ylabel, data, ops, backends, key, log=True, baseline=None):
    fig, ax = plt.subplots(figsize=(11, 5))
    n = len(backends)
    width = 0.8 / n
    x = np.arange(len(ops))
    for i, b in enumerate(backends):
        vals = [float(data[b][op][key]) for op in ops]
        if baseline:
            vals = [v / float(data[baseline][op][key]) for v, op in zip(vals, ops)]
        ax.bar(x + (i - (n - 1) / 2) * width, vals, width, label=b, color=COLORS.get(b))
    if baseline:
        ax.axhline(1.0, color="black", linewidth=0.8, linestyle="--")
    if log:
        ax.set_yscale("log")
    ax.set_xticks(x)
    ax.set_xticklabels(ops)
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.grid(axis="y", alpha=0.3, which="both")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def main(argv):
    out, files = argv[0], argv[1:]
    os.makedirs(out, exist_ok=True)
    data, ops = load(files)
    backends = [b for b in ORDER if b in data] + [b for b in sorted(data) if b not in ORDER]
    ns = lambda v: "%.1f" % v
    ulp = lambda v: ("%.2f" % v) if v < 100 else ("%.3g" % v)

    md = ["# Interval arithmetics: correctness and speed", "",
          "Generated by `IntervalCompare --full` (%s arguments per operation) and `plot_results.py`. "
          "Best value in each row is in bold." % data[backends[0]][ops[0]]["count"], ""]
    md.append(md_table("Time [ns/operation]", data, ops, backends, "ns_per_op", ns))
    base = "filib" if "filib" in data else backends[0]
    md.append("### Time relative to %s (<1 means faster)\n" % base)
    md.append("| op | " + " | ".join(backends) + " |\n|---|" + "---:|" * len(backends))
    for op in ops:
        vals = [float(data[b][op]["ns_per_op"]) / float(data[base][op]["ns_per_op"]) for b in backends]
        best = min(vals)
        md.append("| %s | %s |" % (op, " | ".join(("**%.2f**" if v == best else "%.2f") % v for v in vals)))
    md.append("")
    md.append(md_table("Mean overestimation of the exact hull [ulp]", data, ops, backends, "mean_excess_ulp", ulp))
    md.append(md_table("Maximal overestimation of the exact hull [ulp]", data, ops, backends, "max_excess_ulp", ulp))
    md.append(md_table("Violations (result does not contain the exact hull)", data, ops, backends, "violations", lambda v: "%d" % v))
    md.append("![time](time_ns.png)\n\n![relative time](time_relative.png)\n\n![mean overestimation](overestimation_mean.png)\n\n"
              "![max overestimation](overestimation_max.png)\n")
    with open(os.path.join(out, "results.md"), "w") as fh:
        fh.write("\n".join(md))

    bar_chart(os.path.join(out, "time_ns.png"), "Time per operation (lower is better)", "ns / operation (log scale)",
              data, ops, backends, "ns_per_op")
    bar_chart(os.path.join(out, "time_relative.png"), "Time relative to %s (lower is better)" % base,
              "time / time(%s) (log scale)" % base, data, ops, backends, "ns_per_op", baseline=base)
    bar_chart(os.path.join(out, "overestimation_mean.png"), "Mean overestimation of the exact result (lower is better)",
              "ulp (log scale)", data, ops, backends, "mean_excess_ulp")
    bar_chart(os.path.join(out, "overestimation_max.png"), "Maximal overestimation of the exact result (lower is better)",
              "ulp (log scale)", data, ops, backends, "max_excess_ulp")


if __name__ == "__main__":
    main(sys.argv[1:])
