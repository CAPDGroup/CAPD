#!/usr/bin/env python3
"""Tables (Markdown) and charts (PNG) for the `IntervalCompare --width` results.

Usage: plot_width.py OUTPUT_DIR intervals_width_filib.csv intervals_width_tight.csv [...]

Quality of the enclosure is measured by the diameter of the result:
  * width 0 (point argument): the diameter of the result in ulps (the exact result is a point, so
    the whole diameter is overestimation),
  * width > 0: ratio diam(result) / diam(exact hull) and its excess over 1.
"""
import csv
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ORDER = ["filib", "tight", "native", "cxsc"]
COLORS = {"filib": "#1f77b4", "tight": "#2ca02c", "native": "#d62728", "cxsc": "#ff7f0e"}
FLOOR = 1e-12


def load(files):
    data, ops, widths = {}, [], []
    for f in files:
        with open(f) as fh:
            for row in csv.DictReader(fh):
                w = float(row["width"])
                data.setdefault(row["backend"], {})[(row["op"], w)] = row
                if row["op"] not in ops:
                    ops.append(row["op"])
                if w not in widths:
                    widths.append(w)
    return data, ops, sorted(widths)


def wlabel(w):
    return "point" if w == 0 else "%.0e" % w


def num(row, key):
    return float(row[key])


def fmt_ulp(v):
    return "%.2f" % v if v < 100 else "%.3g" % v


def table(title, data, ops, widths, backends, cell):
    head = "| op | " + " | ".join("%s %s" % (wlabel(w), b) for w in widths for b in backends) + " |"
    lines = ["### " + title, "", head, "|---|" + "---:|" * (len(widths) * len(backends))]
    for op in ops:
        cells = []
        for w in widths:
            vals = [cell(data[b][(op, w)]) for b in backends]
            best = min(v[0] for v in vals)
            worst = max(v[0] for v in vals)
            # bold only a value that is strictly better than another one (no bold for ties)
            cells += [("**%s**" if v[0] == best and best < worst else "%s") % v[1] for v in vals]
        lines.append("| %s | %s |" % (op, " | ".join(cells)))
    return "\n".join(lines) + "\n"


def main(argv):
    out, files = argv[0], argv[1:]
    os.makedirs(out, exist_ok=True)
    data, ops, widths = load(files)
    backends = [b for b in ORDER if b in data] + [b for b in sorted(data) if b not in ORDER]
    pos = [w for w in widths if w > 0]
    count = next(iter(data[backends[0]].values()))["count"]

    md = ["# Quality of enclosures vs. diameter of the argument", "",
          "Generated by `IntervalCompare --full --width` (%s arguments per operation and width) and `plot_width.py`. "
          "Arguments: |x| in [0.25, 4), absolute diameter %s. Best value of each pair is in bold." %
          (count, ", ".join(wlabel(w) for w in widths)), ""]
    md.append(table("Mean overestimation [ulp] (diameter of the result minus diameter of the exact hull)",
                    data, ops, widths, backends,
                    lambda r: (num(r, "mean_excess_ulp"), fmt_ulp(num(r, "mean_excess_ulp")))))
    md.append(table("Maximal overestimation [ulp]", data, ops, widths, backends,
                    lambda r: (num(r, "max_excess_ulp"), fmt_ulp(num(r, "max_excess_ulp")))))
    md.append(table("Mean diameter of the result", data, ops, widths, backends,
                    lambda r: (num(r, "mean_diam"), "%.3e" % num(r, "mean_diam"))))
    md.append(table("Median of diam(result) / diam(exact hull)  (1 = optimal)", data, ops, pos, backends,
                    lambda r: (num(r, "median_ratio"), "%.9f" % num(r, "median_ratio"))))
    md.append(table("Absolute excess of the diameter: mean diam(result) - mean diam(hull)", data, ops, pos, backends,
                    lambda r: (num(r, "mean_diam") - num(r, "mean_hull_diam"),
                               "%.2e" % (num(r, "mean_diam") - num(r, "mean_hull_diam")))))
    md.append(table("Violations (result does not contain the exact hull)", data, ops, widths, backends,
                    lambda r: (num(r, "violations"), "%d" % num(r, "violations"))))
    md.append("![overestimation in ulp](width_excess_ulp.png)\n\n![relative overestimation](width_ratio.png)\n")
    with open(os.path.join(out, "results_width.md"), "w") as fh:
        fh.write("\n".join(md))

    # ---- chart 1: mean overestimation [ulp], one panel per width
    ncols = 2
    nrows = (len(widths) + 1) // 2
    fig, axes = plt.subplots(nrows, ncols, figsize=(12, 4.2 * nrows), sharex=True)
    axes = np.atleast_1d(axes).ravel()
    x = np.arange(len(ops))
    bw = 0.8 / len(backends)
    for ax, w in zip(axes, widths):
        for i, b in enumerate(backends):
            vals = [max(num(data[b][(op, w)], "mean_excess_ulp"), 0.05) for op in ops]
            ax.bar(x + (i - (len(backends) - 1) / 2) * bw, vals, bw, label=b, color=COLORS.get(b))
        ax.set_yscale("log")
        ax.set_title("argument diameter: %s" % wlabel(w))
        ax.set_ylabel("mean overestimation [ulp]")
        ax.set_xticks(x)
        ax.set_xticklabels(ops)
        ax.grid(axis="y", alpha=0.3, which="both")
    for ax in axes[len(widths):]:
        ax.axis("off")
    axes[0].legend()
    fig.suptitle("Mean overestimation of the diameter vs. the exact hull (lower is better)")
    fig.tight_layout()
    fig.savefig(os.path.join(out, "width_excess_ulp.png"), dpi=130)
    plt.close(fig)

    # ---- chart 2: relative overestimation diam(result)/diam(hull) - 1 as a function of the argument diameter
    fig, axes = plt.subplots(1, len(backends), figsize=(5.8 * len(backends), 5), sharey=True)
    axes = np.atleast_1d(axes)
    cmap = plt.get_cmap("tab20")
    for ax, b in zip(axes, backends):
        for k, op in enumerate(ops):
            ys = [max(num(data[b][(op, w)], "median_ratio") - 1.0, FLOOR) for w in pos]
            ax.plot(pos, ys, marker="o", label=op, color=cmap(k))
        ax.plot(pos, [1e-16 / w for w in pos], "k--", linewidth=0.8, label="~1e-16 / w")
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xlabel("argument diameter w")
        ax.set_title(b)
        ax.grid(alpha=0.3, which="both")
    axes[0].set_ylabel("median diam(result)/diam(hull) - 1")
    axes[-1].legend(ncol=2, fontsize=8)
    fig.suptitle("Relative overestimation of the diameter (lower is better)")
    fig.tight_layout()
    fig.savefig(os.path.join(out, "width_ratio.png"), dpi=130)
    plt.close(fig)


if __name__ == "__main__":
    main(sys.argv[1:])
